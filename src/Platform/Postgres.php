<?php

declare(strict_types=1);

namespace Systopic\Db\Platform;

use RuntimeException;
use Systopic\Db\Schema\Column;
use Systopic\Db\Schema\ForeignKey;
use Systopic\Db\Schema\Index;
use Systopic\Db\Schema\Kind;
use Systopic\Db\Schema\Table;

/**
 * Postgres is not here because somebody is migrating tomorrow but as proof:
 * `Kind` and `Column` contain no SQL, and that is exactly why a different
 * dialect falls out of the same class without the declaration knowing about
 * it.
 *
 * Two differences the design predicts:
 *   - `unsigned` does not exist; the value range grows instead
 *     (int -> bigint), otherwise there would be silent loss.
 *   - An enum without a type of its own becomes varchar + CHECK, not ENUM.
 */
final class Postgres implements Platform
{
    public function name(): string
    {
        return 'postgres';
    }

    public function quote(string $identifier): string
    {
        return '"' . str_replace('"', '""', $identifier) . '"';
    }

    public function renderColumn(Column $c): string
    {
        if ($c->autoIncrement) {
            return ($c->kind === Kind::BigInt ? 'bigint' : 'integer')
                . ' GENERATED BY DEFAULT AS IDENTITY NOT NULL';
        }

        $sql = match ($c->kind) {
            // Postgres has no unsigned: better one size up than silently
            // losing half the value range.
            Kind::Int      => $c->unsigned ? 'bigint' : 'integer',
            Kind::BigInt   => 'bigint',
            Kind::Float    => 'double precision',
            Kind::Decimal  => 'numeric(' . ($c->length ?? 10) . ',' . ($c->scale ?? 2) . ')',
            Kind::Bool     => 'boolean',
            Kind::String   => $c->enumCases
                ? 'varchar(' . max(array_map('strlen', $c->enumCases)) . ')'
                : 'varchar(' . ($c->length ?? 255) . ')',
            Kind::Text     => 'text',
            Kind::Json     => 'jsonb',
            Kind::Date     => 'date',
            Kind::DateTime => 'timestamp',
            Kind::Time     => 'time',
            Kind::Binary   => 'bytea',
        };

        $sql .= $c->nullable ? ' NULL' : ' NOT NULL';
        if ($c->default !== null) {
            $sql .= ' DEFAULT ' . $this->literal($c->default);
        }
        return $sql;
    }

    public function createTable(Table $t, bool $withForeignKeys = true): string
    {
        $lines = [];
        foreach ($t->columns as $name => $c) {
            $lines[] = '  ' . $this->quote($name) . ' ' . $this->renderColumn($c);
        }
        $lines[] = '  PRIMARY KEY ('
            . implode(', ', array_map($this->quote(...), $t->key)) . ')';

        foreach ($t->columns as $name => $c) {
            if ($c->enumCases) {
                $values = implode(', ', array_map($this->literal(...), $c->enumCases));
                $lines[] = '  CHECK (' . $this->quote($name) . ' IN (' . $values . '))';
            }
            if ($name !== ($t->key[0] ?? null) && $c->index === Index::Unique) {
                $lines[] = '  UNIQUE (' . $this->quote($name) . ')';
            }
        }

        if ($withForeignKeys) {
            foreach ($t->foreignKeys as $fk) {
                $lines[] = '  FOREIGN KEY (' . $this->quote($fk->column) . ')'
                    . ' REFERENCES ' . $this->quote($fk->table) . ' (' . $this->quote($fk->references) . ')';
            }
        }

        $sql = 'CREATE TABLE ' . $this->quote($t->name) . " (\n" . implode(",\n", $lines) . "\n)";

        // Non-unique indexes are statements of their own in Postgres.
        foreach ($t->columns as $name => $c) {
            if ($name !== ($t->key[0] ?? null) && $c->index === Index::Plain) {
                $sql .= ";\nCREATE INDEX " . $this->quote($this->indexName($t, $name))
                    . ' ON ' . $this->quote($t->name) . ' (' . $this->quote($name) . ')';
            }
        }

        // And here the difference to MySQL becomes visible: Postgres creates
        // **no** index for a foreign key. Without these lines every join over
        // a relation would be a sequential scan.
        foreach (array_keys($t->foreignKeys) as $name) {
            // Not the leftmost key column: the primary key already indexes its
            // own prefix, here as much as on MySQL.
            if ($name === ($t->key[0] ?? null)) {
                continue;
            }
            if (isset($t->columns[$name]) && $t->columns[$name]->index === null) {
                $sql .= ";\nCREATE INDEX " . $this->quote($this->indexName($t, $name))
                    . ' ON ' . $this->quote($t->name) . ' (' . $this->quote($name) . ')';
            }
        }
        return $sql;
    }

    /** Postgres index names are schema-wide, so the table has to be in them. */
    public function indexName(Table $t, string $column): string
    {
        return match ($t->columns[$column]?->index ?? null) {
            Index::Unique => 'uk_' . $t->name . '_' . $column,
            default       => 'ix_' . $t->name . '_' . $column,
        };
    }

    public function addIndex(Table $t, string $column): string
    {
        $c = $t->columns[$column] ?? throw new RuntimeException(
            "column \"$column\" is not declared in {$t->class}"
        );
        if ($c->index === Index::Fulltext) {
            // Deliberately not silently something else: Postgres has no
            // FULLTEXT. It does the same job with a GIN index over
            // to_tsvector(), and which language that is parsed in is a
            // decision nobody should make by accident.
            throw new RuntimeException(
                "fulltext on \"$column\" needs a GIN index over to_tsvector() in Postgres — "
                . 'that has to be written by hand, the language is part of it'
            );
        }
        return 'CREATE ' . ($c->index === Index::Unique ? 'UNIQUE ' : '') . 'INDEX '
            . $this->quote($this->indexName($t, $column))
            . ' ON ' . $this->quote($t->name) . ' (' . $this->quote($column) . ')';
    }

    /** No `ON <table>` — an index name is unique per schema here. */
    public function dropIndex(string $table, string $index): string
    {
        return 'DROP INDEX ' . $this->quote($index);
    }

    /**
     * Postgres has no `FOREIGN_KEY_CHECKS`. The equivalent is to pretend to be
     * a replication target, where triggers — and a foreign key is a trigger
     * here — do not fire. It needs superuser rights, which the MySQL switch
     * does not, so this is close but not free.
     */
    public function foreignKeyChecks(bool $on): string
    {
        return "SET session_replication_role = '" . ($on ? 'origin' : 'replica') . "'";
    }

    /**
     * `NOT EXISTS` rather than MySQL's join form — Postgres has no restriction
     * on reading the table it updates, so the plain correlated subquery says
     * what it means.
     */
    public function clearOrphans(string $table, string $column, ForeignKey $foreignKey): string
    {
        $child  = $this->quote($table);
        $parent = $this->quote($foreignKey->table);
        $ref    = $this->quote($foreignKey->references);
        $col    = $this->quote($column);

        return "UPDATE $child SET $col = NULL"
            . " WHERE $col IS NOT NULL"
            . " AND NOT EXISTS (SELECT 1 FROM $parent p WHERE p.$ref = $child.$col)";
    }

    public function addColumn(Table $t, string $column): string
    {
        $c = $t->columns[$column] ?? throw new RuntimeException(
            "column \"$column\" is not declared in {$t->class}"
        );
        return 'ALTER TABLE ' . $this->quote($t->name)
            . ' ADD COLUMN ' . $this->quote($column) . ' ' . $this->renderColumn($c);
    }

    public function modifyColumn(Table $t, string $column): string
    {
        $c = $t->columns[$column] ?? throw new RuntimeException(
            "column \"$column\" is not declared in {$t->class}"
        );
        // Postgres splits type and nullability into two statements.
        $tabelle = $this->quote($t->name);
        $column  = $this->quote($column);
        $typ     = trim(preg_replace('~\s+(NOT\s+)?NULL.*$~i', '', $this->renderColumn($c)) ?? '');
        return "ALTER TABLE $tabelle ALTER COLUMN $column TYPE $typ;\n"
            . "ALTER TABLE $tabelle ALTER COLUMN $column "
            . ($c->nullable ? 'DROP NOT NULL' : 'SET NOT NULL');
    }

    private function literal(mixed $v): string
    {
        return match (true) {
            is_bool($v)              => $v ? 'true' : 'false',
            is_int($v), is_float($v) => (string) $v,
            default                  => "'" . str_replace("'", "''", (string) $v) . "'",
        };
    }
}
